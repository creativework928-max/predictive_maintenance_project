def load_raw_data(
    raw_data_path: Path,
) -> pd.DataFrame:
    """
    Load the raw CSV dataset.

    The project's DataLoader is preferred when a compatible public method
    exists. pandas.read_csv() is the reliable fallback.
    """
    if not raw_data_path.exists():
        raise FileNotFoundError(
            f"Raw dataset was not found: {raw_data_path}"
        )

    if raw_data_path.suffix.lower() != ".csv":
        raise ValueError(
            "This Task 2 runner currently expects a CSV input file."
        )

    LOGGER.info(
        "Loading raw dataset from: %s",
        raw_data_path,
    )

    if DataLoader is not None:
        try:
            loader = DataLoader()

            candidate_methods = (
                "load_csv",
                "load_data",
                "load",
                "read_csv",
            )

            for method_name in candidate_methods:
                method = getattr(
                    loader,
                    method_name,
                    None,
                )

                if method is None:
                    continue

                try:
                    loaded = method(raw_data_path)
                except TypeError:
                    loaded = method(str(raw_data_path))

                if isinstance(loaded, pd.DataFrame):
                    LOGGER.info(
                        "Dataset loaded using src.data_loader.%s().",
                        method_name,
                    )
                    return loaded

        except Exception as exc:
            LOGGER.warning(
                "Project DataLoader could not be used: %s. "
                "Falling back to pandas.read_csv().",
                exc,
            )

    df = pd.read_csv(raw_data_path)

    LOGGER.info(
        "Dataset loaded using pandas.read_csv()."
    )

    return df


