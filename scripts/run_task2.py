def build_feature_engineer(
    random_state: int,
) -> Any:
    """
    Build the current project's feature engineer.

    The current feature_engineering.py uses
    PredictiveMaintenanceFeatureEngineer directly. It does not use the
    FeatureEngineeringConfig interface assumed by the previous runner.

    random_state is retained in the runner API for reproducibility of the
    overall pipeline; the current feature engineer itself does not require
    a random_state constructor argument.
    """
    del random_state

    if PredictiveMaintenanceFeatureEngineer is None:
        raise ImportError(
            "Could not import PredictiveMaintenanceFeatureEngineer from "
            "src.feature_engineering."
        )

    # The current class accepts these parameters. We explicitly preserve
    # identifiers because the generated datasets should remain traceable.
    try:
        engineer = PredictiveMaintenanceFeatureEngineer(
            add_missing_indicators=True,
            keep_identifiers=True,
        )
    except TypeError:
        # Compatibility fallback for a simpler implementation.
        engineer = PredictiveMaintenanceFeatureEngineer()

    return engineer


def fit_transform_features(
    engineer: Any,
    train_df: pd.DataFrame,
    validation_df: pd.DataFrame,
    test_df: pd.DataFrame,
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Fit feature engineering on training data and transform all partitions.

    IMPORTANT:
    The current FeatureEngineer.transform() accepts only the DataFrame.
    The previous runner incorrectly supplied include_context/include_target,
    which caused an API mismatch. This function now uses the real API.
    """
    LOGGER.info(
        "Fitting feature-engineering transformations on training data only."
    )

    if not hasattr(engineer, "fit"):
        raise AttributeError(
            "Feature engineer must provide a fit() method."
        )

    engineer.fit(train_df)

    if not hasattr(engineer, "transform"):
        raise AttributeError(
            "Feature engineer must provide a transform() method."
        )

    LOGGER.info("Transforming training partition.")
    train_features = engineer.transform(train_df)

    LOGGER.info("Transforming validation partition.")
    validation_features = engineer.transform(validation_df)

    LOGGER.info("Transforming test partition.")
    test_features = engineer.transform(test_df)

    return (
        train_features,
        validation_features,
        test_features,
    )


