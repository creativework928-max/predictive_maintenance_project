def main(
    argv: Optional[Sequence[str]] = None,
) -> int:
    """
    Command-line entry point.

    Returns
    -------
    int
        Process exit code.
    """
    parser = build_argument_parser()
    args = parser.parse_args(argv)

    configure_logging(
        verbose=args.verbose
    )

    # Import after logging is configured so import failures are visible.
    _load_project_components()

    try:
        validate_split_sizes(
            args.train_size,
            args.validation_size,
            args.test_size,
        )

        if args.random_state < 0:
            raise ValueError(
                "--random-state must be non-negative."
            )

        metadata = run_pipeline(
            raw_data_path=args.raw_data.resolve(),
            processed_dir=args.output_dir.resolve(),
            report_dir=args.report_dir.resolve(),
            figure_dir=args.figure_dir.resolve(),
            train_size=args.train_size,
            validation_size=args.validation_size,
            test_size=args.test_size,
            random_state=args.random_state,
            skip_visualizations=args.skip_visualizations,
            skip_reports=args.skip_reports,
        )

        # Core pipeline status.
        core_status = (
            metadata.get("execution", {})
            .get("status", "unknown")
        )

        if core_status != "completed":
            LOGGER.error(
                "Core pipeline finished with status: %s",
                core_status,
            )
            return 1

        visualization_status = (
            metadata.get("artifacts", {})
            .get("visualizations", {})
            .get("status")
        )

        report_status = (
            metadata.get("artifacts", {})
            .get("reports", {})
            .get("status")
        )

        # Do not hide an actual requested visualization/report failure.
        if not args.skip_visualizations:
            if visualization_status == "failed":
                LOGGER.error(
                    "Pipeline data processing succeeded, but visualization "
                    "generation failed."
                )
                return 1

        if not args.skip_reports:
            if report_status == "failed":
                LOGGER.error(
                    "Pipeline data processing succeeded, but report "
                    "generation failed."
                )
                return 1

        return 0

    except FileNotFoundError as exc:
        LOGGER.error(
            "Input/output file error: %s",
            exc,
        )
        return 1

    except ValueError as exc:
        LOGGER.error(
            "Validation/configuration error: %s",
            exc,
        )
        return 1

    except ImportError as exc:
        LOGGER.error(
            "Missing project dependency/module: %s",
            exc,
        )
        return 1

    except KeyboardInterrupt:
        LOGGER.warning(
            "Pipeline interrupted by user."
        )
        return 1

    except Exception as exc:
        LOGGER.error(
            "Unexpected pipeline failure: %s",
            exc,
        )

        LOGGER.debug(
            "Full traceback:\n%s",
            traceback.format_exc(),
        )

        return 2


