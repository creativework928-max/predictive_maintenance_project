# ---------------------------------------------------------------------------
# Main pipeline
# ---------------------------------------------------------------------------

def run_pipeline(
    raw_data_path: Path,
    processed_dir: Path,
    report_dir: Path,
    figure_dir: Path,
    train_size: float,
    validation_size: float,
    test_size: float,
    random_state: int,
    skip_visualizations: bool = False,
    skip_reports: bool = False,
) -> Dict[str, Any]:
    """
    Execute the complete Task 2 batch feature-engineering pipeline.
    """
    pipeline_start = time.perf_counter()

    LOGGER.info("=" * 78)
    LOGGER.info(
        "PREDICTIVE MAINTENANCE - TASK 2 FEATURE ENGINEERING"
    )
    LOGGER.info("=" * 78)

    ensure_directory(processed_dir)
    ensure_directory(report_dir)
    ensure_directory(figure_dir)

    # ------------------------------------------------------------------
    # Step 1: Load raw data
    # ------------------------------------------------------------------

    LOGGER.info("[1/9] Loading raw dataset.")

    raw_df = load_raw_data(
        raw_data_path
    )

    LOGGER.info(
        "Raw dataset shape: %s",
        raw_df.shape,
    )

    raw_df = normalize_column_names(
        raw_df
    )

    target_column = validate_dataframe(
        raw_df,
        require_target=True,
    )

    LOGGER.info(
        "Detected target column: %s",
        target_column,
    )

    # ------------------------------------------------------------------
    # Step 2: Dataset diagnostics
    # ------------------------------------------------------------------

    LOGGER.info("[2/9] Running dataset diagnostics.")

    schema = detect_ai4i_schema(raw_df)

    if schema["is_ai4i_like"]:
        LOGGER.info(
            "AI4I-style schema detected (%d/%d canonical columns).",
            schema["matched_count"],
            schema["expected_count"],
        )

        if len(raw_df) != EXPECTED_AI4I_ROWS:
            LOGGER.warning(
                "AI4I-style dataset contains %d rows; the canonical "
                "AI4I 2020 dataset contains %d rows.",
                len(raw_df),
                EXPECTED_AI4I_ROWS,
            )

    # ------------------------------------------------------------------
    # Step 3: Dataset split
    # ------------------------------------------------------------------

    LOGGER.info(
        "[3/9] Creating train/validation/test partitions."
    )

    train_df, validation_df, test_df = stratified_split(
        df=raw_df,
        target_column=target_column,
        train_size=train_size,
        validation_size=validation_size,
        test_size=test_size,
        random_state=random_state,
    )

    LOGGER.info(
        "Train shape:      %s",
        train_df.shape,
    )

    LOGGER.info(
        "Validation shape: %s",
        validation_df.shape,
    )

    LOGGER.info(
        "Test shape:       %s",
        test_df.shape,
    )

    # ------------------------------------------------------------------
    # Step 4: Feature engineering
    # ------------------------------------------------------------------

    LOGGER.info(
        "[4/9] Performing leakage-safe feature engineering."
    )

    engineer = build_feature_engineer(
        random_state=random_state
    )

    (
        train_features,
        validation_features,
        test_features,
    ) = fit_transform_features(
        engineer=engineer,
        train_df=train_df,
        validation_df=validation_df,
        test_df=test_df,
    )

    LOGGER.info(
        "Engineered train shape:      %s",
        train_features.shape,
    )

    LOGGER.info(
        "Engineered validation shape: %s",
        validation_features.shape,
    )

    LOGGER.info(
        "Engineered test shape:       %s",
        test_features.shape,
    )

    # ------------------------------------------------------------------
    # Step 5: Feature consistency
    # ------------------------------------------------------------------

    LOGGER.info(
        "[5/9] Validating feature consistency."
    )

    train_feature_names = list(train_features.columns)
    validation_feature_names = list(validation_features.columns)
    test_feature_names = list(test_features.columns)

    if train_feature_names != validation_feature_names:
        raise ValueError(
            "Train and validation feature schemas do not match."
        )

    if train_feature_names != test_feature_names:
        raise ValueError(
            "Train and test feature schemas do not match."
        )

    LOGGER.info(
        "Feature schema consistency check passed."
    )

    # ------------------------------------------------------------------
    # Step 6: Leakage checks
    # ------------------------------------------------------------------

    LOGGER.info(
        "[6/9] Running leakage and integrity checks."
    )

    leakage_check = check_for_target_leakage(
        train_features,
        target_column,
    )

    # The feature engineer intentionally returns context columns such as
    # twf/hdf/pwf/osf/rnf. They are NOT model predictors. Build separate
    # leakage-safe predictive matrices for downstream ML/export.
    train_predictive = build_predictive_feature_frame(
        train_features,
        target_column,
    )
    validation_predictive = build_predictive_feature_frame(
        validation_features,
        target_column,
    )
    test_predictive = build_predictive_feature_frame(
        test_features,
        target_column,
    )

    train_safety = assert_predictive_feature_safety(
        train_predictive,
        target_column,
    )
    validation_safety = assert_predictive_feature_safety(
        validation_predictive,
        target_column,
    )
    test_safety = assert_predictive_feature_safety(
        test_predictive,
        target_column,
    )

    if not (
        train_safety["passed"]
        and validation_safety["passed"]
        and test_safety["passed"]
    ):
        raise RuntimeError(
            "Predictive feature leakage detected after sanitization: "
            f"train={train_safety['forbidden_columns_present']}, "
            f"validation={validation_safety['forbidden_columns_present']}, "
            f"test={test_safety['forbidden_columns_present']}"
        )

    if list(train_predictive.columns) != list(validation_predictive.columns):
        raise ValueError(
            "Train and validation predictive feature schemas do not match."
        )

    if list(train_predictive.columns) != list(test_predictive.columns):
        raise ValueError(
            "Train and test predictive feature schemas do not match."
        )

    id_column = find_column(
        raw_df,
        ID_COLUMNS,
    )

    split_check = check_split_disjointness(
        train_df,
        validation_df,
        test_df,
        id_column,
    )

    if not split_check["passed"]:
        LOGGER.warning(
            "ID overlap was detected across data partitions."
        )

    LOGGER.info(
        "Leakage-safe predictive feature check passed: %d features.",
        train_predictive.shape[1],
    )
    # ------------------------------------------------------------------
    # Step 7: Export processed datasets
    # ------------------------------------------------------------------

    LOGGER.info(
        "[7/9] Exporting leakage-safe engineered datasets."
    )

    engineered_path = processed_dir / "engineered_features.csv"
    train_path = processed_dir / "train_features.csv"
    validation_path = processed_dir / "validation_features.csv"
    test_path = processed_dir / "test_features.csv"

    engineered_df = pd.concat(
        [
            train_predictive,
            validation_predictive,
            test_predictive,
        ],
        axis=0,
        ignore_index=True,
    )

    export_dataframe(engineered_df, engineered_path)
    export_dataframe(train_predictive, train_path)
    export_dataframe(validation_predictive, validation_path)
    export_dataframe(test_predictive, test_path)

    # Preserve a context copy for reporting/diagnostics without mixing those
    # labels into the model-ready files.
    context_dir = ensure_directory(
        processed_dir / "context"
    )

    export_dataframe(
        pd.concat(
            [train_features, validation_features, test_features],
            axis=0,
            ignore_index=True,
        ),
        context_dir / "engineered_features_with_context.csv",
    )
    export_dataframe(
        train_features,
        context_dir / "train_features_with_context.csv",
    )
    export_dataframe(
        validation_features,
        context_dir / "validation_features_with_context.csv",
    )
    export_dataframe(
        test_features,
        context_dir / "test_features_with_context.csv",
    )
    # ------------------------------------------------------------------
    # Step 8: Quality, visualizations, and reports
    # ------------------------------------------------------------------

    LOGGER.info(
        "[8/9] Generating quality artifacts, visualizations, and reports."
    )

    quality_result = run_feature_quality_analysis(
        train_features=train_predictive,
        output_dir=report_dir,
    )

    if skip_visualizations:
        visualization_result = {
            "status": "skipped",
            "reason": "Disabled by --skip-visualizations.",
            "generated": {},
            "verified_files": {},
            "count": 0,
        }
    else:
        visualization_result = run_visualizations(
            train_features=train_features,
            output_dir=figure_dir,
            target_column=target_column,
        )

        # A visualization failure should be visible and should not be hidden
        # behind a successful report generation stage.
        if visualization_result.get("status") == "failed":
            LOGGER.error(
                "Visualization stage failed: %s",
                visualization_result.get("reason"),
            )

    # Build metadata before report generation.
    metadata = build_pipeline_metadata(
        raw_df=raw_df,
        train_df=train_df,
        validation_df=validation_df,
        test_df=test_df,
        train_features=train_features,
        validation_features=validation_features,
        test_features=test_features,
        target_column=target_column,
        raw_data_path=raw_data_path,
        random_state=random_state,
        train_size=train_size,
        validation_size=validation_size,
        test_size=test_size,
    )

    # Explicitly collect the files that are really on disk.
    verified_figures = collect_generated_figures(
        figure_dir
    )

    metadata["visualization_files_on_disk"] = {
        title: str(path)
        for title, path in verified_figures.items()
    }

    if skip_reports:
        report_result = {
            "status": "skipped",
            "reason": "Disabled by --skip-reports.",
        }
    else:
        report_result = run_report_generation(
            dataset=train_features,
            report_dir=report_dir,
            figure_dir=figure_dir,
            metadata=metadata,
            figure_mapping=(
                build_default_figure_mapping(figure_dir)
                if build_default_figure_mapping is not None
                else verified_figures
            ),
            train_shape=train_predictive.shape,
            validation_shape=validation_predictive.shape,
            test_shape=test_predictive.shape,
        )


    # ------------------------------------------------------------------
    # Step 9: Final execution summary
    # ------------------------------------------------------------------

    LOGGER.info(
        "[9/9] Writing final execution summary."
    )

    elapsed_seconds = (
        time.perf_counter()
        - pipeline_start
    )

    metadata["execution"] = {
        "status": "completed",
        "elapsed_seconds": elapsed_seconds,
        "completed_at_utc": utc_now_iso(),
    }

    metadata["artifacts"] = {
        "engineered_features": str(engineered_path),
        "train_features": str(train_path),
        "validation_features": str(validation_path),
        "test_features": str(test_path),
        "report_directory": str(report_dir),
        "figure_directory": str(figure_dir),
        "feature_quality": quality_result,
        "visualizations": visualization_result,
        "reports": report_result,
    }

    metadata["validation"] = {
        "feature_schema_consistent": True,
        "target_leakage_check": leakage_check,
        "predictive_feature_safety": {
            "train": train_safety,
            "validation": validation_safety,
            "test": test_safety,
        },
        "split_disjointness": split_check,
        "train_missing_cells": int(
            train_features.isna().sum().sum()
        ),
        "validation_missing_cells": int(
            validation_features.isna().sum().sum()
        ),
        "test_missing_cells": int(
            test_features.isna().sum().sum()
        ),
        "verified_figure_count": len(
            verified_figures
        ),
    }

    summary_path = (
        report_dir
        / "task2_execution_summary.json"
    )

    write_json(
        metadata,
        summary_path,
    )

    LOGGER.info(
        "Execution summary written to: %s",
        summary_path,
    )

    # The pipeline's core data processing completed. We deliberately keep
    # that status separate from optional visualization/report failures so
    # the exported engineered datasets remain valid artifacts.
    LOGGER.info("=" * 78)
    LOGGER.info(
        "TASK 2 PIPELINE COMPLETED"
    )
    LOGGER.info(
        "Elapsed time: %.2f seconds",
        elapsed_seconds,
    )
    LOGGER.info(
        "Verified visualization files: %d",
        len(verified_figures),
    )
    LOGGER.info("=" * 78)

    return metadata


