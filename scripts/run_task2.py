def check_for_target_leakage(
    features: pd.DataFrame,
    target_column: str,
) -> Dict[str, Any]:
    """
    Check the full engineered frame while distinguishing context columns
    from actual predictive columns.

    The feature engineer keeps AI4I labels in the returned frame for
    traceability. Therefore the full frame may contain twf/hdf/pwf/osf/rnf;
    the predictive matrix must not.
    """
    predictive = build_predictive_feature_frame(
        features,
        target_column,
    )

    safety = assert_predictive_feature_safety(
        predictive,
        target_column,
    )

    return {
        "leakage_columns_present": safety["forbidden_columns_present"],
        "predictive_feature_count_checked": safety["feature_count"],
        "context_columns_retained": [
            column
            for column in features.columns
            if column not in predictive.columns
        ],
        "passed": safety["passed"],
    }


def check_split_disjointness(
    train_df: pd.DataFrame,
    validation_df: pd.DataFrame,
    test_df: pd.DataFrame,
    id_column: Optional[str],
) -> Dict[str, Any]:
    """
    Verify that ID values do not overlap across partitions.

    For the canonical AI4I dataset, UID is row-level and unique, so overlap
    checking is useful as an integrity check. It is not interpreted as a
    machine-time sequence.
    """
    if id_column is None:
        return {
            "checked": False,
            "reason": "No suitable ID column detected.",
            "passed": True,
        }

    if id_column not in train_df.columns:
        return {
            "checked": False,
            "reason": f"ID column '{id_column}' is not present.",
            "passed": True,
        }

    train_ids = set(
        train_df[id_column].dropna().tolist()
    )

    validation_ids = set(
        validation_df[id_column].dropna().tolist()
    )

    test_ids = set(
        test_df[id_column].dropna().tolist()
    )

    train_validation_overlap = train_ids.intersection(
        validation_ids
    )

    train_test_overlap = train_ids.intersection(
        test_ids
    )

    validation_test_overlap = validation_ids.intersection(
        test_ids
    )

    passed = not any(
        (
            train_validation_overlap,
            train_test_overlap,
            validation_test_overlap,
        )
    )

    return {
        "checked": True,
        "id_column": id_column,
        "passed": passed,
        "train_validation_overlap": len(
            train_validation_overlap
        ),
        "train_test_overlap": len(
            train_test_overlap
        ),
        "validation_test_overlap": len(
            validation_test_overlap
        ),
    }


