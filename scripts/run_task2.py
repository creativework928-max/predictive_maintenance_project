def utc_now_iso() -> str:
    """Return the current UTC timestamp in ISO-8601 format."""
    return datetime.now(timezone.utc).isoformat()


def ensure_directory(path: Path) -> Path:
    """Create a directory if it does not already exist."""
    path.mkdir(parents=True, exist_ok=True)
    return path


def safe_json_value(value: Any) -> Any:
    """Convert common NumPy/Pandas/dataclass values into JSON-safe objects."""
    if value is None:
        return None

    if isinstance(value, Path):
        return str(value)

    if isinstance(value, (np.integer,)):
        return int(value)

    if isinstance(value, (np.floating,)):
        if np.isnan(value):
            return None
        return float(value)

    if isinstance(value, (np.bool_,)):
        return bool(value)

    if isinstance(value, pd.Timestamp):
        return value.isoformat()

    if isinstance(value, np.ndarray):
        return value.tolist()

    if isinstance(value, pd.Series):
        return value.tolist()

    if isinstance(value, pd.DataFrame):
        return value.to_dict(orient="records")

    if is_dataclass(value):
        return {
            key: safe_json_value(val)
            for key, val in asdict(value).items()
        }

    if isinstance(value, Mapping):
        return {
            str(key): safe_json_value(val)
            for key, val in value.items()
        }

    if isinstance(value, (list, tuple, set)):
        return [safe_json_value(item) for item in value]

    return value


def write_json(
    data: Dict[str, Any],
    output_path: Path,
) -> None:
    """Write a dictionary to a formatted JSON file."""
    ensure_directory(output_path.parent)

    with output_path.open(
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(
            safe_json_value(data),
            file,
            indent=2,
            ensure_ascii=False,
        )


def find_column(
    df: pd.DataFrame,
    candidates: Sequence[str],
) -> Optional[str]:
    """
    Find the first matching column from a list of candidates.

    Matching is case-sensitive first, followed by normalized
    case-insensitive comparison.
    """
    for candidate in candidates:
        if candidate in df.columns:
            return candidate

    normalized = {
        str(column).strip().lower(): column
        for column in df.columns
    }

    for candidate in candidates:
        key = str(candidate).strip().lower()

        if key in normalized:
            return normalized[key]

    return None


def normalize_column_names(
    df: pd.DataFrame,
) -> pd.DataFrame:
    """
    Normalize known AI4I column names.

    The transformation is intentionally conservative.
    """
    result = df.copy()

    known_mappings = {
        "UID": "uid",
        "Product ID": "product_id",
        "Type": "type",
        "Air temperature [K]": "air_temperature_k",
        "Process temperature [K]": "process_temperature_k",
        "Rotational speed [rpm]": "rotational_speed_rpm",
        "Torque [Nm]": "torque_nm",
        "Tool wear [min]": "tool_wear_min",
        "Machine failure": "machine_failure",
        "TWF": "twf",
        "HDF": "hdf",
        "PWF": "pwf",
        "OSF": "osf",
        "RNF": "rnf",
        "Failure Type": "failure_type",
    }

    rename_map = {
        original: normalized
        for original, normalized in known_mappings.items()
        if original in result.columns
    }

    if rename_map:
        result = result.rename(columns=rename_map)

    return result


def validate_split_sizes(
    train_size: float,
    validation_size: float,
    test_size: float,
) -> None:
    """Validate train/validation/test proportions."""
    sizes = (
        train_size,
        validation_size,
        test_size,
    )

    if any(size <= 0 or size >= 1 for size in sizes):
        raise ValueError(
            "Train, validation, and test sizes must each be greater than "
            "0 and less than 1."
        )

    total = sum(sizes)

    if not np.isclose(total, 1.0, atol=1e-8):
        raise ValueError(
            "Train, validation, and test sizes must sum to 1.0. "
            f"Received {total:.6f}."
        )


def validate_dataframe(
    df: pd.DataFrame,
    require_target: bool = True,
) -> str:
    """
    Validate the loaded dataset.

    Returns
    -------
    str
        Detected target column.
    """
    if not isinstance(df, pd.DataFrame):
        raise TypeError("Expected a pandas DataFrame.")

    if df.empty:
        raise ValueError("The input dataset is empty.")

    if df.shape[1] < 2:
        raise ValueError(
            "The input dataset must contain at least two columns."
        )

    duplicated_columns = df.columns[
        df.columns.duplicated()
    ].tolist()

    if duplicated_columns:
        raise ValueError(
            "Duplicate column names detected: "
            f"{duplicated_columns}"
        )

    target_column = find_column(
        df,
        TARGET_COLUMN_CANDIDATES,
    )

    if require_target and target_column is None:
        raise ValueError(
            "Could not identify the target column. Expected one of: "
            f"{TARGET_COLUMN_CANDIDATES}"
        )

    if target_column is not None:
        target_values = df[target_column].dropna()

        if target_values.empty:
            raise ValueError(
                f"Target column '{target_column}' contains only missing values."
            )

        if target_values.nunique() < 2:
            raise ValueError(
                f"Target column '{target_column}' contains fewer than "
                "two unique values."
            )

    return target_column or ""


def detect_ai4i_schema(
    df: pd.DataFrame,
) -> Dict[str, Any]:
    """Detect whether supplied data follows the AI4I-style schema."""
    required_ai4i_columns = {
        "uid",
        "product_id",
        "type",
        "air_temperature_k",
        "process_temperature_k",
        "rotational_speed_rpm",
        "torque_nm",
        "tool_wear_min",
        "machine_failure",
    }

    present = set(df.columns)
    matched = required_ai4i_columns.intersection(present)

    return {
        "is_ai4i_like": len(matched) >= 7,
        "matched_ai4i_columns": sorted(matched),
        "matched_count": len(matched),
        "expected_count": len(required_ai4i_columns),
    }


