def run_feature_quality_analysis(
    train_features: pd.DataFrame,
    output_dir: Path,
) -> Dict[str, Any]:
    """
    Execute feature-quality analysis when the optional analyzer exists.

    The quality stage is downstream of the core pipeline. If its API is
    different, the main datasets and visualizations are still preserved.
    """
    result: Dict[str, Any] = {
        "status": "skipped",
        "reason": None,
    }

    if FeatureQualityAnalyzer is None:
        result["reason"] = (
            "FeatureQualityAnalyzer is unavailable or src.feature_quality "
            "could not be imported."
        )
        LOGGER.warning(result["reason"])
        return result

    ensure_directory(output_dir)

    try:
        analyzer = FeatureQualityAnalyzer()
    except Exception as exc:
        result["status"] = "failed"
        result["reason"] = str(exc)
        LOGGER.exception(
            "Could not initialize FeatureQualityAnalyzer."
        )
        return result

    candidate_methods = (
        "analyze",
        "generate_quality_report",
        "run",
        "fit_transform",
    )

    for method_name in candidate_methods:
        method = getattr(
            analyzer,
            method_name,
            None,
        )

        if method is None:
            continue

        try:
            analysis = method(train_features)

            if isinstance(analysis, pd.DataFrame):
                quality_path = (
                    output_dir
                    / "feature_quality_report.csv"
                )

                analysis.to_csv(
                    quality_path,
                    index=False,
                    encoding="utf-8",
                )

                result.update(
                    {
                        "status": "completed",
                        "method": method_name,
                        "output": str(quality_path),
                    }
                )

            elif analysis is not None:
                result.update(
                    {
                        "status": "completed",
                        "method": method_name,
                        "result_type": type(analysis).__name__,
                    }
                )

            else:
                result.update(
                    {
                        "status": "completed",
                        "method": method_name,
                    }
                )

            LOGGER.info(
                "Feature-quality analysis completed using %s().",
                method_name,
            )

            return result

        except TypeError:
            continue

        except Exception as exc:
            result["status"] = "failed"
            result["reason"] = str(exc)

            LOGGER.exception(
                "Feature-quality method %s() failed.",
                method_name,
            )

            return result

    result["reason"] = (
        "No compatible public feature-quality method was found."
    )

    LOGGER.warning(result["reason"])

    return result


