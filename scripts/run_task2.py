def run_visualizations(
    train_features: pd.DataFrame,
    output_dir: Path,
    target_column: str,
) -> Dict[str, Any]:
    """
    Generate Task 2 visualizations using the actual public API.

    The current visualization module exposes:
        generate_task2_visualizations(...)

    It does NOT expose:
        FeatureVisualization(...)

    This distinction was the primary reason the previous runner did not
    generate images.
    """
    result: Dict[str, Any] = {
        "status": "skipped",
        "reason": None,
        "generated": {},
        "output_directory": str(output_dir),
    }

    if generate_task2_visualizations is None:
        result["status"] = "failed"
        result["reason"] = (
            "src.visualization.generate_task2_visualizations could not "
            "be imported."
        )
        LOGGER.error(result["reason"])
        return result

    ensure_directory(output_dir)

    # A real timestamp/machine_id is deliberately not invented for AI4I.
    timestamp_column = (
        "timestamp"
        if "timestamp" in train_features.columns
        else None
    )

    machine_id_column = None

    for candidate in (
        "machine_id",
        "Machine ID",
    ):
        if candidate in train_features.columns:
            machine_id_column = candidate
            break

    try:
        generated = generate_task2_visualizations(
            train_features,
            output_directory=output_dir,
            target_column=target_column,
            timestamp_column=timestamp_column,
            machine_id_column=machine_id_column,
        )

        if generated is None:
            generated = {}

        generated_paths = {
            str(name): str(Path(path))
            for name, path in dict(generated).items()
        }

        # Explicitly verify the actual files on disk. This prevents a
        # "completed" status when a plotting function returns a path that
        # was not successfully written.
        existing = collect_generated_figures(output_dir)

        result.update(
            {
                "status": "completed" if existing else "failed",
                "generated": generated_paths,
                "verified_files": {
                    title: str(path)
                    for title, path in existing.items()
                },
                "count": len(existing),
            }
        )

        if existing:
            LOGGER.info(
                "Visualization generation completed: %d PNG files found.",
                len(existing),
            )

            for title, path in existing.items():
                LOGGER.info(
                    "  IMAGE OK: %s -> %s",
                    title,
                    path,
                )

        else:
            result["reason"] = (
                "Visualization function completed but no PNG files were "
                f"found in {output_dir}."
            )

            LOGGER.error(result["reason"])

        return result

    except Exception as exc:
        result["status"] = "failed"
        result["reason"] = str(exc)

        LOGGER.exception(
            "Task 2 visualization generation failed."
        )

        return result


