def stratified_split(
    df: pd.DataFrame,
    target_column: str,
    train_size: float,
    validation_size: float,
    test_size: float,
    random_state: int,
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Create a reproducible stratified train/validation/test split.
    """
    validate_split_sizes(
        train_size,
        validation_size,
        test_size,
    )

    try:
        from sklearn.model_selection import train_test_split
    except ImportError as exc:
        raise ImportError(
            "scikit-learn is required for train/validation/test splitting."
        ) from exc

    if target_column not in df.columns:
        raise KeyError(
            f"Target column '{target_column}' not found."
        )

    y = df[target_column]

    if y.isna().any():
        raise ValueError(
            "The target contains missing values. "
            "Clean the target before creating supervised-learning splits."
        )

    class_counts = y.value_counts()

    if len(class_counts) < 2:
        raise ValueError(
            "The target must contain at least two classes."
        )

    if class_counts.min() < 3:
        raise ValueError(
            "Stratified train/validation/test splitting requires at least "
            "3 observations in every target class. "
            f"Class counts: {class_counts.to_dict()}"
        )

    train_val_df, test_df = train_test_split(
        df,
        test_size=test_size,
        random_state=random_state,
        stratify=y,
    )

    relative_validation_size = validation_size / (
        train_size + validation_size
    )

    train_df, validation_df = train_test_split(
        train_val_df,
        test_size=relative_validation_size,
        random_state=random_state,
        stratify=train_val_df[target_column],
    )

    train_df = train_df.sort_index()
    validation_df = validation_df.sort_index()
    test_df = test_df.sort_index()

    return (
        train_df.reset_index(drop=True),
        validation_df.reset_index(drop=True),
        test_df.reset_index(drop=True),
    )


def summarize_split(
    df: pd.DataFrame,
    target_column: str,
) -> Dict[str, Any]:
    """Produce a concise summary for one data partition."""
    summary: Dict[str, Any] = {
        "rows": int(len(df)),
        "columns": int(df.shape[1]),
        "missing_cells": int(df.isna().sum().sum()),
        "missing_rate": float(df.isna().mean().mean()),
    }

    if target_column in df.columns:
        distribution = (
            df[target_column]
            .value_counts(dropna=False)
            .sort_index()
        )

        summary["target_distribution"] = {
            str(key): int(value)
            for key, value in distribution.items()
        }

        if len(df) > 0:
            positive_count = 0

            for key, value in distribution.items():
                is_positive = (
                    key == 1
                    or key is True
                    or str(key).strip().lower() in {
                        "1",
                        "true",
                        "yes",
                        "failure",
                    }
                )

                if is_positive:
                    positive_count += int(value)

            summary["positive_rate"] = float(
                positive_count / len(df)
            )

    return summary


