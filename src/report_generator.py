def prepare_dataset_summary(
    df: pd.DataFrame,
    *,
    target_column: Optional[str] = None,
) -> pd.DataFrame:
    """
    Prepare high-level dataset statistics.
    """

    if not isinstance(
        df,
        pd.DataFrame,
    ):
        raise TypeError(
            "df must be a pandas DataFrame."
        )

    n_rows = len(df)
    n_columns = len(df.columns)

    numeric_columns = df.select_dtypes(
        include=[np.number]
    ).columns

    categorical_columns = [
        column
        for column in df.columns
        if column not in numeric_columns
    ]

    missing_cells = int(
        df.isna().sum().sum()
    )

    duplicate_rows = int(
        df.duplicated().sum()
    )

    if target_column in df.columns:

        target_missing = int(
            df[target_column].isna().sum()
        )

        target_unique = int(
            df[target_column]
            .nunique(
                dropna=True
            )
        )

    else:

        target_missing = None
        target_unique = None

    summary = pd.DataFrame(
        {
            "Metric": [
                "Rows",
                "Columns",
                "Numeric columns",
                "Categorical columns",
                "Missing cells",
                "Duplicate rows",
                "Target column",
                "Target missing values",
                "Target unique values",
            ],
            "Value": [
                n_rows,
                n_columns,
                len(numeric_columns),
                len(categorical_columns),
                missing_cells,
                duplicate_rows,
                target_column
                if target_column
                else "Not supplied",
                target_missing,
                target_unique,
            ],
        }
    )

    return summary


def prepare_feature_inventory(
    df: pd.DataFrame,
    *,
    target_column: Optional[str] = None,
    exclude_columns: Optional[
        Iterable[str]
    ] = None,
) -> pd.DataFrame:
    """
    Build a feature inventory for reporting.
    """

    exclude = set(
        exclude_columns or []
    )

    if target_column:
        exclude.add(
            target_column
        )

    rows = []

    for column in df.columns:

        if column in exclude:
            continue

        series = df[column]

        numeric = pd.api.types.is_numeric_dtype(
            series
        )

        rows.append(
            {
                "Feature": column,
                "Data type": str(
                    series.dtype
                ),
                "Numeric": (
                    "Yes"
                    if numeric
                    else "No"
                ),
                "Missing": int(
                    series.isna().sum()
                ),
                "Missing %": (
                    float(
                        series.isna().mean()
                        * 100
                    )
                ),
                "Unique values": int(
                    series.nunique(
                        dropna=True
                    )
                ),
            }
        )

    return pd.DataFrame(rows)


