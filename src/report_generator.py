def _set_cell_shading(
    cell,
    fill: str,
) -> None:
    """
    Apply background shading to a DOCX table cell.
    """

    if not DOCX_AVAILABLE:
        return

    tc_pr = cell._tc.get_or_add_tcPr()

    shd = OxmlElement(
        "w:shd"
    )

    shd.set(
        qn("w:fill"),
        fill,
    )

    tc_pr.append(shd)


def _set_cell_text_color(
    cell,
    color: str,
) -> None:
    """
    Apply text color to all paragraphs in a DOCX cell.
    """

    if not DOCX_AVAILABLE:
        return

    for paragraph in cell.paragraphs:

        for run in paragraph.runs:

            run.font.color.rgb = (
                __import__(
                    "docx"
                ).shared.RGBColor.from_string(
                    color
                )
            )


def _set_cell_bold(
    cell,
    bold: bool = True,
) -> None:
    """
    Set all cell text to bold/normal.
    """

    if not DOCX_AVAILABLE:
        return

    for paragraph in cell.paragraphs:

        for run in paragraph.runs:

            run.bold = bold


def add_docx_table(
    document,
    df: Optional[pd.DataFrame],
    *,
    max_rows: int = 100,
    font_size: int = 8,
) -> None:
    """
    Add a DataFrame as a formatted DOCX table.
    """

    if not DOCX_AVAILABLE:
        raise RuntimeError(
            "python-docx is required to generate DOCX reports."
        )

    if df is None or df.empty:

        paragraph = document.add_paragraph(
            "No information available."
        )

        paragraph.runs[0].italic = True

        return

    working = _truncate_dataframe(
        df,
        max_rows,
    )

    table = document.add_table(
        rows=1,
        cols=len(working.columns),
    )

    table.style = "Table Grid"

    header_cells = table.rows[0].cells

    for index, column in enumerate(
        working.columns
    ):

        cell = header_cells[index]

        cell.text = str(column)

        _set_cell_shading(
            cell,
            "17365D",
        )

        _set_cell_bold(
            cell,
            True,
        )

        _set_cell_text_color(
            cell,
            "FFFFFF",
        )

        cell.vertical_alignment = (
            WD_CELL_VERTICAL_ALIGNMENT.CENTER
        )

        for paragraph in cell.paragraphs:

            for run in paragraph.runs:

                run.font.size = Pt(
                    font_size
                )

    for _, row in working.iterrows():

        cells = table.add_row().cells

        for index, value in enumerate(row):

            cells[index].text = (
                _format_value(
                    value
                )
            )

            cells[index].vertical_alignment = (
                WD_CELL_VERTICAL_ALIGNMENT.CENTER
            )

            for paragraph in cells[index].paragraphs:

                for run in paragraph.runs:

                    run.font.size = Pt(
                        font_size
                    )

    if len(df) > max_rows:

        paragraph = document.add_paragraph(
            f"Showing first {max_rows:,} "
            f"of {len(df):,} rows."
        )

        paragraph.runs[0].italic = True


def add_docx_heading(
    document,
    text: str,
    level: int = 1,
) -> None:
    """
    Add a formatted DOCX heading.
    """

    heading = document.add_heading(
        text,
        level=level,
    )

    for run in heading.runs:

        run.font.name = "Aptos"

        if level == 1:
            run.font.size = Pt(20)
        elif level == 2:
            run.font.size = Pt(15)
        else:
            run.font.size = Pt(12)


def add_docx_bullet_list(
    document,
    items: Sequence[str],
) -> None:
    """
    Add bullet points to a DOCX document.
    """

    for item in items:

        paragraph = document.add_paragraph(
            style="List Bullet"
        )

        paragraph.add_run(
            str(item)
        )


def add_docx_callout(
    document,
    title: str,
    text: str,
) -> None:
    """
    Add a visually distinct DOCX callout.
    """

    table = document.add_table(
        rows=1,
        cols=1,
    )

    table.style = "Table Grid"

    cell = table.cell(
        0,
        0,
    )

    _set_cell_shading(
        cell,
        "F2F7FC",
    )

    paragraph = cell.paragraphs[0]

    run = paragraph.add_run(
        title + "\n"
    )

    run.bold = True
    run.font.size = Pt(11)

    run = paragraph.add_run(
        text
    )

    run.font.size = Pt(10)


def add_docx_figure(
    document,
    figure_path: str | Path,
    caption: str,
    *,
    width_inches: float = 6.5,
) -> None:
    """
    Add a figure and caption to a DOCX report.
    """

    figure_path = Path(
        figure_path
    )

    if not figure_path.exists():
        return

    paragraph = document.add_paragraph()

    paragraph.alignment = (
        WD_ALIGN_PARAGRAPH.CENTER
    )

    run = paragraph.add_run()

    run.add_picture(
        str(figure_path),
        width=Inches(
            width_inches
        ),
    )

    caption_paragraph = (
        document.add_paragraph()
    )

    caption_paragraph.alignment = (
        WD_ALIGN_PARAGRAPH.CENTER
    )

    caption_run = (
        caption_paragraph.add_run(
            caption
        )
    )

    caption_run.italic = True
    caption_run.font.size = Pt(9)


