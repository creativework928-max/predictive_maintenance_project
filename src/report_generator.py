# Save report manifest
# ---------------------------------------------------------------------

def save_report_manifest(
    generated_reports: Mapping[str, str | Path],
    *,
    output_path: str | Path = (
        "reports/report_manifest.json"
    ),
    metadata: Optional[
        ReportMetadata
    ] = None,
) -> Path:
    """
    Save a machine-readable report manifest.
    """

    output_path = Path(
        output_path
    )

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    manifest = {
        "generated_at": datetime.now(
            timezone.utc
        ).isoformat(),
        "reports": {
            name: str(
                Path(path)
            )
            for name, path
            in generated_reports.items()
        },
    }

    if metadata is not None:

        manifest[
            "metadata"
        ] = {
            "project_name": metadata.project_name,
            "title": metadata.title,
            "dataset_name": metadata.dataset_name,
            "dataset_source": metadata.dataset_source,
            "dataset_doi": metadata.dataset_doi,
            "time_series_mode": metadata.time_series_mode,
            "timestamp_column": metadata.timestamp_column,
            "machine_id_column": metadata.machine_id_column,
            "target_column": metadata.target_column,
            "project_version": metadata.project_version,
        }

    output_path.write_text(
        json.dumps(
            manifest,
            indent=4,
        ),
        encoding="utf-8",
    )

    return output_path


