def dataframe_to_html(
    df: Optional[pd.DataFrame],
    *,
    max_rows: int = 100,
    decimals: int = 4,
    empty_message: str = (
        "No information available."
    ),
) -> str:
    """
    Convert a DataFrame into a professional HTML table.
    """

    if df is None or df.empty:

        return (
            '<div class="empty-message">'
            f"{escape(empty_message)}"
            "</div>"
        )

    working = _truncate_dataframe(
        df,
        max_rows,
    )

    html = [
        '<div class="table-container">',
        '<table class="data-table">',
        "<thead>",
        "<tr>",
    ]

    for column in working.columns:

        html.append(
            "<th>"
            + escape(
                str(column)
            )
            + "</th>"
        )

    html.extend(
        [
            "</tr>",
            "</thead>",
            "<tbody>",
        ]
    )

    for _, row in working.iterrows():

        html.append("<tr>")

        for value in row:

            html.append(
                "<td>"
                + escape(
                    _format_value(
                        value,
                        decimals=decimals,
                    )
                )
                + "</td>"
            )

        html.append("</tr>")

    html.extend(
        [
            "</tbody>",
            "</table>",
            "</div>",
        ]
    )

    if len(df) > max_rows:

        html.append(
            '<p class="table-note">'
            f"Showing first {max_rows:,} of "
            f"{len(df):,} rows."
            "</p>"
        )

    return "\n".join(html)


def metric_card(
    label: str,
    value: Any,
    description: Optional[str] = None,
) -> str:
    """
    Generate an HTML metric card.
    """

    description_html = ""

    if description:

        description_html = (
            '<div class="metric-description">'
            + escape(description)
            + "</div>"
        )

    return (
        '<div class="metric-card">'
        '<div class="metric-label">'
        + escape(label)
        + "</div>"
        '<div class="metric-value">'
        + escape(_format_value(value))
        + "</div>"
        + description_html
        + "</div>"
    )


def section(
    section_id: str,
    title: str,
    content: str,
) -> str:
    """
    Generate a report section.
    """

    return (
        f'<section id="{escape(section_id)}" '
        'class="report-section">'
        f"<h2>{escape(title)}</h2>"
        f"{content}"
        "</section>"
    )


