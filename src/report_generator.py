def generate_all_reports(
    *,
    metadata: Optional[
        ReportMetadata
    ] = None,
    config: Optional[
        ReportConfig
    ] = None,
    dataset: pd.DataFrame,
    quality_results: Optional[
        Mapping[str, pd.DataFrame]
    ] = None,
    engineered_features: Optional[
        Sequence[str]
    ] = None,
    feature_descriptions: Optional[
        Mapping[str, str]
    ] = None,
    figures: Optional[
        Mapping[str, str | Path]
    ] = None,
    train_shape: Optional[
        tuple[int, int]
    ] = None,
    validation_shape: Optional[
        tuple[int, int]
    ] = None,
    test_shape: Optional[
        tuple[int, int]
    ] = None,
    methodology_notes: Optional[
        Sequence[str]
    ] = None,
    leakage_notes: Optional[
        Sequence[str]
    ] = None,
    realtime_notes: Optional[
        Sequence[str]
    ] = None,
) -> dict[str, Path]:
    """
    Generate both HTML and DOCX reports.

    Returns
    -------
    dict[str, pathlib.Path]
        Generated report paths.
    """

    metadata = (
        metadata
        or ReportMetadata()
    )

    config = (
        config
        or ReportConfig()
    )

    generated: dict[str, Path] = {}

    html_path = generate_html_report(
        metadata=metadata,
        config=config,
        dataset=dataset,
        quality_results=quality_results,
        engineered_features=engineered_features,
        feature_descriptions=feature_descriptions,
        figures=figures,
        train_shape=train_shape,
        validation_shape=validation_shape,
        test_shape=test_shape,
        methodology_notes=methodology_notes,
        leakage_notes=leakage_notes,
        realtime_notes=realtime_notes,
    )

    generated[
        "html"
    ] = html_path

    if config.generate_docx:

        docx_path = generate_docx_report(
            metadata=metadata,
            config=config,
            dataset=dataset,
            quality_results=quality_results,
            engineered_features=engineered_features,
            feature_descriptions=feature_descriptions,
            figures=figures,
            train_shape=train_shape,
            validation_shape=validation_shape,
            test_shape=test_shape,
            methodology_notes=methodology_notes,
            leakage_notes=leakage_notes,
            realtime_notes=realtime_notes,
        )

        generated[
            "docx"
        ] = docx_path

    return generated


