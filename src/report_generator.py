def _ensure_directory(
    directory: str | Path,
) -> Path:
    """
    Create and return a directory.
    """

    path = Path(directory)

    path.mkdir(
        parents=True,
        exist_ok=True,
    )

    return path


def _safe_value(
    value: Any,
) -> Any:
    """
    Convert numpy/pandas values into JSON/HTML-safe Python values.
    """

    if value is None:
        return None

    if isinstance(
        value,
        (np.integer,),
    ):
        return int(value)

    if isinstance(
        value,
        (np.floating,),
    ):
        if np.isnan(value):
            return None

        if np.isinf(value):
            return None

        return float(value)

    if isinstance(
        value,
        (np.bool_,),
    ):
        return bool(value)

    if pd.isna(value):
        return None

    if isinstance(
        value,
        (pd.Timestamp,),
    ):
        return value.isoformat()

    return value


def _format_value(
    value: Any,
    decimals: int = 4,
) -> str:
    """
    Format values consistently for reports.
    """

    value = _safe_value(value)

    if value is None:
        return "—"

    if isinstance(
        value,
        float,
    ):

        if abs(value) >= 100000:
            return f"{value:,.2e}"

        return f"{value:,.{decimals}f}"

    if isinstance(
        value,
        int,
    ):
        return f"{value:,}"

    return str(value)


def _escape(
    value: Any,
) -> str:
    """
    HTML-escape a value.
    """

    return escape(
        _format_value(value)
    )


def _validate_dataframe(
    df: Optional[pd.DataFrame],
    name: str,
) -> None:
    """
    Validate optional DataFrame inputs.
    """

    if df is None:
        return

    if not isinstance(
        df,
        pd.DataFrame,
    ):
        raise TypeError(
            f"{name} must be a pandas DataFrame."
        )


def _truncate_dataframe(
    df: Optional[pd.DataFrame],
    max_rows: int,
) -> pd.DataFrame:
    """
    Safely truncate a DataFrame for report presentation.
    """

    if df is None:
        return pd.DataFrame()

    if max_rows <= 0:
        return df.iloc[0:0].copy()

    return df.head(max_rows).copy()


def _relative_path(
    path: str | Path,
    base_directory: str | Path,
) -> str:
    """
    Convert a file path to a report-relative path.
    """

    path = Path(path)
    base_directory = Path(base_directory)

    try:
        return str(
            path.resolve().relative_to(
                base_directory.resolve()
            )
        ).replace(
            "\\",
            "/",
        )

    except ValueError:
        return path.name


